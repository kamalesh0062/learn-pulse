import React, { useState, useEffect } from 'react';
import { useSearchParams } from 'react-router-dom';
import { courseApi, difficultyApi, revisionApi, getErrorMessage } from '../services/api';
import { DifficultTopic, RevisionKit, Topic } from '../types';
import { LoadingState } from '../components/common/LoadingState';
import { EmptyState } from '../components/common/EmptyState';
import { Sparkles, BookOpen, Layers, CheckCircle2, RotateCw, RefreshCw, AlertCircle, HelpCircle, XCircle } from 'lucide-react';

interface TopicChoice {
  id: number;
  title: string;
  lectureTitle: string;
  difficulty?: DifficultTopic;
}

const SOURCE_LABELS: Record<RevisionKit['source'], string> = {
  gemini: 'Generated by Google Gemini',
  openai: 'Generated by OpenAI',
  local: 'Offline kit — built from your lecturer\'s topic notes and the quiz questions you have answered (no AI provider is configured)'
};

export const RevisionPage: React.FC = () => {
  const [searchParams, setSearchParams] = useSearchParams();
  const [choices, setChoices] = useState<TopicChoice[]>([]);
  const [loadingTopics, setLoadingTopics] = useState<boolean>(true);
  const [kit, setKit] = useState<RevisionKit | null>(null);
  const [generating, setGenerating] = useState<boolean>(false);
  const [error, setError] = useState<string | null>(null);
  const [flippedCardId, setFlippedCardId] = useState<number | null>(null);
  const [practiceAnswers, setPracticeAnswers] = useState<Record<number, string>>({});

  const topicParam = Number(searchParams.get('topic')) || null;

  // Topic list: every topic in the catalog, hardest-for-this-student first
  useEffect(() => {
    const load = async () => {
      try {
        const [courses, difficulties] = await Promise.all([courseApi.getCourses(), difficultyApi.getMyTopics()]);
        const byTopic = new Map(difficulties.map((d) => [d.topic_id, d]));
        const all: TopicChoice[] = courses.flatMap((c) =>
          (c.lectures || []).flatMap((l) =>
            (l.topics || []).map((t: Topic) => ({
              id: t.id,
              title: t.title,
              lectureTitle: l.title,
              difficulty: byTopic.get(t.id)
            }))
          )
        );
        all.sort((a, b) => (b.difficulty?.difficulty_score ?? -1) - (a.difficulty?.difficulty_score ?? -1));
        setChoices(all);
      } catch (err) {
        console.error("Revision topic load error:", err);
        setError(getErrorMessage(err, "Could not load your topics."));
      } finally {
        setLoadingTopics(false);
      }
    };
    load();
  }, []);

  const selected = choices.find((c) => c.id === topicParam) || choices[0] || null;
  const selectedId = selected?.id ?? null;

  const generateKit = async (topicId: number) => {
    setGenerating(true);
    setError(null);
    setFlippedCardId(null);
    setPracticeAnswers({});
    try {
      setKit(await revisionApi.generateKit({ topicId }));
    } catch (err) {
      console.error("AI Revision kit error:", err);
      setKit(null);
      setError(getErrorMessage(err, "The revision kit could not be generated."));
    } finally {
      setGenerating(false);
    }
  };

  useEffect(() => {
    if (selectedId) generateKit(selectedId);
  }, [selectedId]);

  if (loadingTopics) return <LoadingState message="Loading your topics..." />;

  if (!selected) {
    return (
      <EmptyState
        title="No topics to revise yet"
        description="Revision kits are built per lecture topic. No topics have been published yet."
      />
    );
  }

  return (
    <div className="space-y-6">
      {/* Header Banner */}
      <div className="glass-card p-6 rounded-3xl border border-dark-border flex flex-col md:flex-row items-start md:items-center justify-between gap-4">
        <div>
          <div className="inline-flex items-center space-x-2 px-3 py-1 rounded-full bg-purple-500/10 text-purple-400 border border-purple-500/30 text-xs font-semibold mb-2">
            <Sparkles className="w-3.5 h-3.5" />
            <span>AI Learning Assistant</span>
          </div>
          <h1 className="text-2xl font-extrabold text-white font-heading">
            AI Revision Kit Generator ✨
          </h1>
          <p className="text-xs text-slate-400 mt-1">
            Summary, flashcards and practice questions for a topic. Topics are listed hardest-for-you first.
          </p>
        </div>

        <div className="flex items-center space-x-2 w-full md:w-auto">
          <select
            value={selected.id}
            onChange={(e) => setSearchParams({ topic: e.target.value })}
            className="bg-dark-card border border-dark-border rounded-xl px-3 py-2 text-xs text-slate-200 focus:outline-none focus:border-brand-500 w-full md:w-72"
          >
            {choices.map((c) => (
              <option key={c.id} value={c.id}>
                {c.title}{c.difficulty ? ` — ${c.difficulty.difficulty_label} (${c.difficulty.difficulty_score})` : ''}
              </option>
            ))}
          </select>
          <button
            onClick={() => generateKit(selected.id)}
            disabled={generating}
            className="gradient-btn px-4 py-2 text-xs font-bold text-white rounded-xl flex items-center space-x-1.5 shrink-0 disabled:opacity-50"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${generating ? 'animate-spin' : ''}`} />
            <span>Regenerate</span>
          </button>
        </div>
      </div>

      {error && (
        <div className="p-3 rounded-xl bg-rose-500/10 border border-rose-500/30 text-rose-400 text-xs flex items-center space-x-2">
          <AlertCircle className="w-4 h-4 shrink-0" />
          <span>{error}</span>
        </div>
      )}

      {generating ? (
        <LoadingState message="Building your revision kit..." />
      ) : (
        kit && (
          <div className="space-y-6">
            <div className={`px-4 py-2.5 rounded-xl border text-[11px] ${
              kit.source === 'local'
                ? 'bg-amber-500/10 border-amber-500/30 text-amber-300'
                : 'bg-purple-500/10 border-purple-500/30 text-purple-300'
            }`}>
              {SOURCE_LABELS[kit.source]}
            </div>

            {/* Summary Section */}
            <div className="glass-card p-6 rounded-3xl border border-dark-border space-y-3">
              <h3 className="text-sm font-bold text-white font-heading flex items-center gap-2">
                <BookOpen className="w-4 h-4 text-brand-400" />
                Summary: {kit.topic_title}
              </h3>
              <p className="text-xs text-slate-300 leading-relaxed bg-dark-bg/60 p-4 rounded-2xl border border-dark-border whitespace-pre-line">
                {kit.summary}
              </p>
            </div>

            {/* Key Takeaways */}
            {kit.key_takeaways.length > 0 && (
              <div className="glass-card p-6 rounded-3xl border border-dark-border space-y-3">
                <h3 className="text-sm font-bold text-white font-heading flex items-center gap-2">
                  <CheckCircle2 className="w-4 h-4 text-emerald-400" />
                  Key Takeaways
                </h3>
                <div className="grid grid-cols-1 md:grid-cols-3 gap-3">
                  {kit.key_takeaways.map((takeaway, idx) => (
                    <div key={idx} className="p-3.5 rounded-2xl bg-dark-bg/60 border border-dark-border text-xs text-slate-300">
                      <span className="font-bold text-brand-400 font-mono block mb-1">Takeaway #{idx + 1}</span>
                      {takeaway}
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Interactive Flashcards */}
            {kit.flashcards.length > 0 && (
              <div className="glass-card p-6 rounded-3xl border border-dark-border space-y-4">
                <h3 className="text-sm font-bold text-white font-heading flex items-center gap-2">
                  <Layers className="w-4 h-4 text-purple-400" />
                  Revision Flashcards (click a card to flip it)
                </h3>

                <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                  {kit.flashcards.map((fc) => {
                    const isFlipped = flippedCardId === fc.id;
                    return (
                      <div
                        key={fc.id}
                        onClick={() => setFlippedCardId(isFlipped ? null : fc.id)}
                        className={`min-h-[160px] p-5 rounded-2xl border transition-all cursor-pointer flex flex-col justify-between ${
                          isFlipped
                            ? 'bg-purple-900/30 border-purple-500 text-white shadow-glow'
                            : 'bg-dark-bg/60 border-dark-border text-slate-200 hover:border-slate-600'
                        }`}
                      >
                        <div className="flex justify-between items-center text-[10px] font-mono text-purple-400 font-bold">
                          <span>FLASHCARD #{fc.id}</span>
                          <RotateCw className="w-3.5 h-3.5" />
                        </div>

                        <div className="text-xs font-semibold my-2">
                          {isFlipped ? (
                            <span className="text-emerald-300 font-normal">{fc.answer}</span>
                          ) : (
                            <span>{fc.question}</span>
                          )}
                        </div>

                        <div className="text-[10px] text-slate-400 text-right">
                          {isFlipped ? 'Click to view question' : 'Click to reveal answer'}
                        </div>
                      </div>
                    );
                  })}
                </div>
              </div>
            )}

            {/* Practice Questions */}
            {kit.practice_questions.length > 0 && (
              <div className="glass-card p-6 rounded-3xl border border-dark-border space-y-4">
                <h3 className="text-sm font-bold text-white font-heading flex items-center gap-2">
                  <HelpCircle className="w-4 h-4 text-brand-400" />
                  Practice Questions (not graded)
                </h3>

                {kit.practice_questions.map((pq) => {
                  const chosen = practiceAnswers[pq.id];
                  return (
                    <div key={pq.id} className="p-4 rounded-2xl bg-dark-bg/60 border border-dark-border space-y-3">
                      <div className="text-xs font-semibold text-white">{pq.question}</div>
                      <div className="grid grid-cols-1 md:grid-cols-2 gap-2">
                        {pq.options.map((option, idx) => {
                          const letter = 'ABCD'[idx];
                          const isCorrect = letter === pq.correct;
                          let style = 'bg-dark-card border-dark-border text-slate-300 hover:border-slate-600';
                          if (chosen) {
                            if (isCorrect) style = 'bg-emerald-500/20 border-emerald-500 text-white';
                            else if (letter === chosen) style = 'bg-rose-500/20 border-rose-500 text-white';
                            else style = 'bg-dark-card border-dark-border text-slate-500';
                          }
                          return (
                            <button
                              key={letter}
                              disabled={!!chosen}
                              onClick={() => setPracticeAnswers({ ...practiceAnswers, [pq.id]: letter })}
                              className={`text-left px-3 py-2 rounded-xl border text-[11px] transition-all ${style}`}
                            >
                              {option}
                            </button>
                          );
                        })}
                      </div>
                      {chosen && (
                        <div className={`text-[11px] flex items-start gap-1.5 ${chosen === pq.correct ? 'text-emerald-400' : 'text-rose-400'}`}>
                          {chosen === pq.correct ? <CheckCircle2 className="w-3.5 h-3.5 mt-0.5 shrink-0" /> : <XCircle className="w-3.5 h-3.5 mt-0.5 shrink-0" />}
                          <span>
                            {chosen === pq.correct ? 'Correct.' : `Not quite — the answer is ${pq.correct}.`} {pq.explanation}
                          </span>
                        </div>
                      )}
                    </div>
                  );
                })}
              </div>
            )}
          </div>
        )
      )}
    </div>
  );
};
